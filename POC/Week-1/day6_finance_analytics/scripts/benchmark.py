def percentile(values: list[float], p: float) -> float:
    ordered = sorted(values)
    if not ordered:
        return 0.0
    index = (len(ordered) - 1) * p
    lower = int(index)
    upper = min(lower + 1, len(ordered) - 1)
    fraction = index - lower
    return ordered[lower] * (1 - fraction) + ordered[upper] * fraction


def timed(callable_, iterations: int) -> list[float]:
    measurements = []
    for _ in range(iterations):
        started = time.perf_counter_ns()
        callable_()
        measurements.append((time.perf_counter_ns() - started) / 1_000_000)
    return measurements


def summarize(values: list[float]) -> dict[str, float]:
    return {
        "mean_ms": statistics.fmean(values),
        "p50_ms": percentile(values, 0.50),
        "p95_ms": percentile(values, 0.95),
        "min_ms": min(values),
        "max_ms": max(values),
    }


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--iterations", type=int, default=300)
    parser.add_argument("--output", type=Path, default=ROOT / "METRICS.md")
    args = parser.parse_args()

    settings = Settings.from_env()
    seed(settings)
    database = Database(settings.database_url)
    cache = MemoryTTLCache()
    metrics = MetricsRegistry()
    period_from = date(2025, 1, 1)
    period_to = date(2025, 12, 1)

    with database.session_factory() as session:
        uncached = timed(
            lambda: repository.variance_summary(
                session,
                period_from=period_from,
                period_to=period_to,
                department_code=None,
            ),
            args.iterations,
        )

        service.get_variance_summary(
            session,
            cache,
            metrics,
            period_from=period_from,
            period_to=period_to,
            department_code=None,
            ttl_seconds=3600,
        )
        cached = timed(
            lambda: service.get_variance_summary(
                session,
                cache,
                metrics,
                period_from=period_from,
                period_to=period_to,
                department_code=None,
                ttl_seconds=3600,
            ),
            args.iterations,
        )

        summary_rows = repository.variance_summary(
            session,
            period_from=period_from,
            period_to=period_to,
            department_code=None,
        )
        source_totals = repository.reconciliation_totals(session)
        summary_budget = sum(Decimal(str(row["budget"])) for row in summary_rows)
        summary_actual = sum(Decimal(str(row["actual"])) for row in summary_rows)
        budget_error = abs(summary_budget - source_totals["budget_total"])
        actual_error = abs(summary_actual - source_totals["actual_total"])

        flagged, _ = repository.top_exceptions(
            session,
            period_from=period_from,
            period_to=period_to,
            department_code=None,
            min_amount=Decimal("1000"),
            min_score=Decimal("25"),
            limit=100_000,
            cursor=None,
        )
        flagged_spend = sum(Decimal(str(row["amount"])) for row in flagged)
        total_spend = source_totals["actual_total"]
        flagged_share = flagged_spend * Decimal("100") / total_spend
        stats_result = approval_amount_welch_test(session)

    uncached_summary = summarize(uncached)
    cached_summary = summarize(cached)
    speedup = uncached_summary["p50_ms"] / cached_summary["p50_ms"]
    cache_snapshot = metrics.snapshot()

    markdown = f"""# Measured Metrics

These measurements were generated by `scripts/benchmark.py` on the bundled deterministic seed dataset. They are not production claims.

## Environment

- Python: {platform.python_version()}
- Platform: {platform.platform()}
- Database profile: `{settings.database_url}`
- Cache profile for this benchmark: in-process TTL cache implementing the same JSON/versioned-key contract as Redis
- Dataset: 8 departments, 24 cost centres, 288 monthly budgets, 30 vendors, 2,330 expenses
- Iterations per latency path: {args.iterations}

## Latency

| Path | Mean (ms) | p50 (ms) | p95 (ms) | Min (ms) | Max (ms) |
|---|---:|---:|---:|---:|---:|
| Direct analytical SQL, no cache | {uncached_summary['mean_ms']:.4f} | {uncached_summary['p50_ms']:.4f} | {uncached_summary['p95_ms']:.4f} | {uncached_summary['min_ms']:.4f} | {uncached_summary['max_ms']:.4f} |
| Warm versioned cache | {cached_summary['mean_ms']:.4f} | {cached_summary['p50_ms']:.4f} | {cached_summary['p95_ms']:.4f} | {cached_summary['min_ms']:.4f} | {cached_summary['max_ms']:.4f} |

Measured p50 speed-up: **{speedup:.2f}x**.

## Quality and operational metrics

| Metric | Measured result | Meaning |
|---|---:|---|
| Budget reconciliation absolute error | {budget_error:.2f} | Aggregated API-query budget equals source budget total |
| Actual reconciliation absolute error | {actual_error:.2f} | Aggregated API-query actual equals source expense total |
| Warm-cache hit ratio | {cache_snapshot['cache_hit_ratio'] * 100:.2f}% | Hits after one priming miss in this benchmark |
| Exception count | {len(flagged):,} | Transactions meeting the documented amount and composite-score rule |
| Exception spend share | {flagged_share:.2f}% | Share of total spend represented by flagged transactions; this is a triage metric, not confirmed fraud or waste |
| Welch-test p-value | {stats_result.p_value:.8f} | Synthetic approved vs non-approved amount comparison |
| Mean-difference 95% CI | [{stats_result.ci_95_low:,.2f}, {stats_result.ci_95_high:,.2f}] | Estimated non-approved minus approved mean amount under Welch assumptions |

## Full-stack benchmark placeholder

Run the Docker profile and capture PostgreSQL plus Redis endpoint latency with:

```bash
python scripts/http_benchmark.py --base-url http://localhost:8000 --iterations 300
```

Do not copy the SQLite/in-memory numbers into a production claim. Record machine type, PostgreSQL version, Redis version, concurrent users, dataset size, and cold/warm state.
"""
    args.output.write_text(markdown, encoding="utf-8")
    print(markdown)
    database.dispose()


if __name__ == "__main__":
    main()
